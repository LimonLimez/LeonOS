			leonos_dom_name_equals_ascii(name, "template") ||
			leonos_dom_name_equals_ascii(name, "base") ||
			leonos_dom_name_equals_ascii(name, "param") ||
			leonos_dom_name_equals_ascii(name, "source") ||

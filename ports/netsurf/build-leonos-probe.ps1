		unsigned char c1 = (unsigned char) text[*index];
		if ((c1 & 0xc0u) == 0x80u) {
			*index += 1u;
			return ((unsigned int)(c & 0x1fu) << 6) |
					(unsigned int)(c1 & 0x3fu);
		}
		return '?';
	}
	if ((c & 0xf0u) == 0xe0u && *index + 1u < length) {
		unsigned char c1 = (unsigned char) text[*index];
		unsigned char c2 = (unsigned char) text[*index + 1u];
		if ((c1 & 0xc0u) == 0x80u && (c2 & 0xc0u) == 0x80u) {

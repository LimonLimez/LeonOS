static bool leonos_css_name_char(char c)
{
	return (c >= 'a' && c <= 'z') ||
	       (c >= 'A' && c <= 'Z') ||
	       (c >= '0' && c <= '9') ||
	       c == '-' || c == '_';
}

static bool leonos_css_space(char c)
{
	return c == ' ' || c == '\t' || c == '\r' ||
	       c == '\n' || c == '\f';
}

static void leonos_css_trim(const char **start, const char **end)
{
	while (*start < *end && leonos_css_space(**start)) {
		*start += 1;
	}
	while (*end > *start && leonos_css_space((*end)[-1])) {
		*end -= 1;
	}
}

static void leonos_css_vars_free(struct leonos_css_var *vars)
{
	free(vars);
}

static char leonos_css_lower_ascii(char c)
{
	if (c >= 'A' && c <= 'Z') {
		return (char)(c - 'A' + 'a');
	}
	return c;
}

static bool leonos_css_region_starts_ci(const char *start,
		const char *end,
		const char *needle)
{
	while (*needle != 0) {
		if (start >= end ||
		    leonos_css_lower_ascii(*start) !=
		    leonos_css_lower_ascii(*needle)) {
			return false;
		}
		start++;
		needle++;
	}

	return true;
}

static bool leonos_css_region_contains_ci(const char *start,
		const char *end,
		const char *needle)
{
	size_t needle_len = strlen(needle);
	const char *limit;
	const char *p;

	if (needle_len == 0) {
		return true;
	}
	if ((size_t)(end - start) < needle_len) {
		return false;
	}

	limit = end - needle_len;
	for (p = start; p <= limit; p++) {
		if (leonos_css_region_starts_ci(p, end, needle)) {
			return true;
		}
	}

	return false;
}

static bool leonos_css_dark_media_header(const char *at,
		const char *limit,
		const char **brace_out)
{
	const char *p = at + 1;
	const char *header_end;

	while (p < limit && leonos_css_space(*p)) {
		p++;
	}
	if (!leonos_css_region_starts_ci(p, limit, "media")) {
		return false;
	}
	p += 5;
	if (p < limit && leonos_css_name_char(*p)) {
		return false;
	}

	header_end = p;
	while (header_end < limit &&
	       *header_end != '{' &&
	       *header_end != ';' &&
	       *header_end != '}') {
		header_end++;
	}
	if (header_end >= limit || *header_end != '{') {
		return false;
	}

	*brace_out = header_end;
	return leonos_css_region_contains_ci(p, header_end,
			"prefers-color-scheme") &&
	       leonos_css_region_contains_ci(p, header_end, "dark");
}

static bool leonos_css_in_prefers_dark_media(const char *css,
		const char *pos)
{
	const char *p = css;
	int depth = 0;
	int dark_depth = -1;
	bool pending_dark_media = false;

	while (p < pos && *p != 0) {
		if (p + 1 < pos && p[0] == '/' && p[1] == '*') {
			p += 2;
			while (p + 1 < pos &&
			       !(p[0] == '*' && p[1] == '/')) {
				p++;
			}
			if (p + 1 < pos) {
				p += 2;
			}
			continue;
		}

		if (*p == '"' || *p == '\'') {
			char quote = *p++;
			while (p < pos && *p != 0) {
				if (*p == '\\' && p + 1 < pos) {
					p += 2;
				} else if (*p == quote) {
					p++;
					break;
				} else {
					p++;
				}
			}
			continue;
		}

		if (*p == '@') {
			const char *brace = NULL;
			if (leonos_css_dark_media_header(p, pos, &brace)) {
				pending_dark_media = true;
			}
		}

		if (*p == '{') {
			depth++;
			if (pending_dark_media) {
				dark_depth = depth;
				pending_dark_media = false;
			}
		} else if (*p == '}') {
			if (dark_depth == depth) {
				dark_depth = -1;
			}
			if (depth > 0) {
				depth--;
			}
			pending_dark_media = false;
		} else if (*p == ';') {
			pending_dark_media = false;
		}

		p++;
	}

	return dark_depth >= 0;
}

static size_t leonos_css_var_collect(const char *css,
		struct leonos_css_var *vars,
		size_t max_vars)
{
	const char *p = css;
	size_t count = 0;

	while ((p = strstr(p, "--")) != NULL) {
		const char *name_start = p;
		const char *name_end = p + 2;
		const char *q;
		const char *value_start;
		const char *value_end;
		size_t name_len;
		size_t value_len;

		if (leonos_css_in_prefers_dark_media(css, p)) {
			p += 2;
			continue;
		}

		while (leonos_css_name_char(*name_end)) {
			name_end++;
		}

		q = name_end;
		while (leonos_css_space(*q)) {
			q++;
		}
		if (*q != ':') {
			p = name_end;
			continue;
		}

		value_start = q + 1;
		value_end = value_start;
		while (*value_end != 0 &&
		       *value_end != ';' &&
		       *value_end != '}') {
			value_end++;
		}

		leonos_css_trim(&value_start, &value_end);
		name_len = (size_t)(name_end - name_start);
		value_len = (size_t)(value_end - value_start);
		if (name_len > 2 && name_len < sizeof(vars[0].name) &&
		    value_len > 0 && value_len < sizeof(vars[0].value)) {
			size_t index;
			for (index = 0; index < count; index++) {
				if (strlen(vars[index].name) == name_len &&
				    strncmp(vars[index].name, name_start,
					    name_len) == 0) {
					break;
				}
			}
			if (index == max_vars) {
				break;
			}
			if (index == count) {
				count++;
			}
			memcpy(vars[index].name, name_start, name_len);
			vars[index].name[name_len] = 0;
			memcpy(vars[index].value, value_start, value_len);
			vars[index].value[value_len] = 0;
		}

		p = value_end;
	}

	return count;
}

static const char *leonos_css_var_lookup(const struct leonos_css_var *vars,
		size_t count,
		const char *name_start,
		const char *name_end)
{
	size_t name_len = (size_t)(name_end - name_start);
	size_t i;

	for (i = 0; i < count; i++) {
		if (strlen(vars[i].name) == name_len &&
		    strncmp(vars[i].name, name_start, name_len) == 0) {
			return vars[i].value;
		}
	}

	return NULL;
}

static bool leonos_css_buffer_append(char **out,
		size_t *out_len,
		size_t *out_cap,
		const char *data,
		size_t data_len)
{
	if (*out_len + data_len + 1 > *out_cap) {
		size_t new_cap = *out_cap;
		char *new_out;
		while (*out_len + data_len + 1 > new_cap) {
			new_cap *= 2;
		}
		new_out = realloc(*out, new_cap);
		if (new_out == NULL) {
			return false;
		}
		*out = new_out;
		*out_cap = new_cap;
	}

	memcpy(*out + *out_len, data, data_len);
	*out_len += data_len;
	(*out)[*out_len] = 0;
	return true;
}

static const char *leonos_css_find_function_end(const char *start,
		const char *end)
{
	const char *p = start;
	int depth = 1;

	while (p < end) {
		if (*p == '(') {
			depth++;
		} else if (*p == ')') {
			depth--;
			if (depth == 0) {
				return p;
			}
		}
		p++;
	}

	return NULL;
}

static const char *leonos_css_find_top_comma(const char *start,
		const char *end)
{
	const char *p = start;
	int depth = 0;

	while (p < end) {
		if (*p == '(') {
			depth++;
		} else if (*p == ')' && depth > 0) {
			depth--;
		} else if (*p == ',' && depth == 0) {
			return p;
		}
		p++;
	}

	return NULL;
}

static char *leonos_css_expand_vars_once(const char *css,
		const struct leonos_css_var *vars,
		size_t var_count)
{
	const char *p = css;
	const char *end = css + strlen(css);
	size_t out_cap = (size_t)(end - css) + 1024;
	size_t out_len = 0;
	char *out = malloc(out_cap);

	if (out == NULL) {
		return NULL;
	}
	out[0] = 0;

	while (p < end) {
		if ((end - p) >= 4 && strncmp(p, "var(", 4) == 0) {
			const char *inner_start = p + 4;
			const char *inner_end =
				leonos_css_find_function_end(inner_start, end);
			const char *comma;
			const char *name_start;
			const char *name_end;
			const char *replacement = NULL;
			const char *fallback_start = NULL;
			const char *fallback_end = NULL;

			if (inner_end != NULL) {
				comma = leonos_css_find_top_comma(inner_start,
						inner_end);
				name_start = inner_start;
				name_end = comma != NULL ? comma : inner_end;
				leonos_css_trim(&name_start, &name_end);
				if ((name_end - name_start) > 2 &&
				    name_start[0] == '-' &&
				    name_start[1] == '-') {
					replacement = leonos_css_var_lookup(vars,
							var_count,
							name_start,
							name_end);
				}

				if (replacement == NULL && comma != NULL) {
					fallback_start = comma + 1;
					fallback_end = inner_end;
					leonos_css_trim(&fallback_start,
							&fallback_end);
				}

				if (replacement != NULL) {
					if (!leonos_css_buffer_append(&out,
							&out_len, &out_cap,
							replacement,
							strlen(replacement))) {
						free(out);
						return NULL;
					}
					p = inner_end + 1;
					continue;
				}
				if (fallback_start != NULL &&
				    fallback_start < fallback_end) {
					if (!leonos_css_buffer_append(&out,
							&out_len, &out_cap,
							fallback_start,
							(size_t)(fallback_end -
								fallback_start))) {
						free(out);
						return NULL;
					}
					p = inner_end + 1;
					continue;
				}
			}
		}

		if (!leonos_css_buffer_append(&out, &out_len, &out_cap, p, 1)) {
			free(out);
			return NULL;
		}
		p++;
	}

	return out;
}


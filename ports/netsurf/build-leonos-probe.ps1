function ConvertTo-CStringLiteral {
    param([string] $Text)

    $Sb = [System.Text.StringBuilder]::new()
    foreach ($Ch in $Text.ToCharArray()) {
        if ($Ch -eq '\') {
            [void] $Sb.Append("\\")
        } elseif ($Ch -eq '"') {
            [void] $Sb.Append('\"')
        } elseif ($Ch -eq "`n") {
            [void] $Sb.Append("\n")
        } elseif ($Ch -eq "`r") {
            [void] $Sb.Append("\r")
        } elseif ([int][char]$Ch -lt 32 -or [int][char]$Ch -gt 126) {
            [void] $Sb.Append(("\x{0:X2}" -f [int][char]$Ch))
        } else {
            [void] $Sb.Append($Ch)
        }
    }
    return $Sb.ToString()
}


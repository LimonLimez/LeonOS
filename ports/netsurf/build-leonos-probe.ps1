function Write-NetSurfCByteInclude {
    param(
        [string] $InputPath,
        [string] $OutputPath,
        [string] $SymbolName
    )

    $Bytes = [System.IO.File]::ReadAllBytes($InputPath)
    $Sb = [System.Text.StringBuilder]::new()
    [void] $Sb.AppendLine("/* Generated by ports/netsurf/build-leonos-probe.ps1 */")
    [void] $Sb.AppendLine(("static const unsigned char {0}[] = {{" -f $SymbolName))
    for ($Offset = 0; $Offset -lt $Bytes.Length; $Offset += 12) {
        $Chunk = @()
        for ($Index = 0; $Index -lt 12 -and ($Offset + $Index) -lt $Bytes.Length; $Index += 1) {
            $Chunk += ("0x{0:x2}" -f $Bytes[$Offset + $Index])
        }
        [void] $Sb.AppendLine(("    {0}," -f ([string]::Join(", ", $Chunk))))
    }
    [void] $Sb.AppendLine("};")
    [void] $Sb.AppendLine(("static const unsigned int {0}_len = {1};" -f $SymbolName, $Bytes.Length))
    [System.IO.File]::WriteAllText($OutputPath, $Sb.ToString(), [System.Text.Encoding]::ASCII)
}

function Ensure-NetSurfDuktapeGeneratedFiles {
    $NetSurfRoot = Join-Path $VendorPath "netsurf"

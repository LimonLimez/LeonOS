/**
 * Parse background_image
 *
 * \param c	  Parsing context
 * \param vector  Vector of tokens to process
 * \param ctx	  Pointer to vector iteration context
 * \param result  resulting style
 * \return CSS_OK on success,
 *	   CSS_NOMEM on memory exhaustion,
 *	   CSS_INVALID if the input is not valid
 *
 * Post condition: \a *ctx is updated with the next token to process
 *		   If the input is invalid, then \a *ctx remains unchanged.
 */
css_error css__parse_background_image(css_language *c,
		const parserutils_vector *vector, int32_t *ctx,
		css_style *result)
{
	int32_t orig_ctx = *ctx;
	int32_t list_ctx;
	css_error error;
	const css_token *token;
	const css_token *uri_token = NULL;
	bool consumed_component = false;
	bool found_uri = false;
	bool match;

	consumeWhitespace(vector, ctx);
	token = parserutils_vector_peek(vector, *ctx);
	if (token == NULL) {
		*ctx = orig_ctx;
		return CSS_INVALID;
	}

	if ((token->type == CSS_TOKEN_IDENT) &&
			(lwc_string_caseless_isequal(
			token->idata, c->strings[INHERIT],
			&match) == lwc_error_ok && match)) {
		parserutils_vector_iterate(vector, ctx);
		return css_stylesheet_style_inherit(result,
				CSS_PROP_BACKGROUND_IMAGE);

	} else if ((token->type == CSS_TOKEN_IDENT) &&
			(lwc_string_caseless_isequal(
			token->idata, c->strings[INITIAL],
			&match) == lwc_error_ok && match)) {
		parserutils_vector_iterate(vector, ctx);
		return css_stylesheet_style_initial(result,
				CSS_PROP_BACKGROUND_IMAGE);

	} else if ((token->type == CSS_TOKEN_IDENT) &&
			(lwc_string_caseless_isequal(
			token->idata, c->strings[REVERT],
			&match) == lwc_error_ok && match)) {
		parserutils_vector_iterate(vector, ctx);
		return css_stylesheet_style_revert(result,
				CSS_PROP_BACKGROUND_IMAGE);

	} else if ((token->type == CSS_TOKEN_IDENT) &&
			(lwc_string_caseless_isequal(
			token->idata, c->strings[UNSET],
			&match) == lwc_error_ok && match)) {
		parserutils_vector_iterate(vector, ctx);
		return css_stylesheet_style_unset(result,
				CSS_PROP_BACKGROUND_IMAGE);
	}

	list_ctx = *ctx;
	while (true) {
		int32_t item_ctx;

		consumeWhitespace(vector, &list_ctx);
		item_ctx = list_ctx;
		token = parserutils_vector_iterate(vector, &list_ctx);
		if (token == NULL) {
			break;
		}

		if (token->type == CSS_TOKEN_URI) {
			if (!found_uri) {
				uri_token = token;
				found_uri = true;
			}
			consumed_component = true;
		} else if (token->type == CSS_TOKEN_FUNCTION) {
			leonos_css_skip_function_value(vector, &list_ctx);
			consumed_component = true;
		} else if (leonos_css_ident_is(c, token, NONE)) {
			consumed_component = true;
		} else {
			if (!consumed_component) {
				*ctx = orig_ctx;
				return CSS_INVALID;
			}
			list_ctx = item_ctx;
			break;
		}

		consumeWhitespace(vector, &list_ctx);
		token = parserutils_vector_peek(vector, list_ctx);
		if (tokenIsChar(token, ',')) {
			parserutils_vector_iterate(vector, &list_ctx);
			continue;
		}
		break;
	}

	if (!consumed_component) {
		*ctx = orig_ctx;
		return CSS_INVALID;
	}

	*ctx = list_ctx;
	if (found_uri) {
		error = leonos_css_append_background_uri(c, uri_token, result);
	} else {
		error = css__stylesheet_style_appendOPV(result,
				CSS_PROP_BACKGROUND_IMAGE,
				0,
				BACKGROUND_IMAGE_NONE);
	}

	if (error != CSS_OK) {
		*ctx = orig_ctx;
	}

	return error;
}


function Sync-Leo1ImageSize {
    param([byte[]] $Bytes)
    if ($Bytes.Length -lt 20) {
        throw "LEO1 image is too small to patch."
    }
    $ImageSize = $Bytes.Length
    $Bytes[12] = [byte] ($ImageSize -band 0xFF)
    $Bytes[13] = [byte] (($ImageSize -shr 8) -band 0xFF)
    $Bytes[14] = [byte] (($ImageSize -shr 16) -band 0xFF)
    $Bytes[15] = [byte] (($ImageSize -shr 24) -band 0xFF)
    return $Bytes
}

function Ensure-LibParserUtilsGeneratedFiles {
    $ParserUtilsRoot = Join-Path $VendorPath "libparserutils"
    $AliasesInc = Join-Path $ParserUtilsRoot "src\charset\aliases.inc"
    if (Test-Path -LiteralPath $AliasesInc) {
        return
    }

    $AliasesFile = Join-Path $ParserUtilsRoot "build\Aliases"
    if (-not (Test-Path -LiteralPath $AliasesFile)) {
        throw "libparserutils aliases source missing at $AliasesFile."
    }

    function ConvertTo-AliasKey {
        param([string] $Value)
        return (($Value.ToLowerInvariant()) -replace '[^a-z0-9]', '')
    }

    function Escape-CString {
        param([string] $Value)
        return (($Value -replace '\\', '\\') -replace '"', '\"')
    }

    $Rows = @()
    foreach ($Line in Get-Content -LiteralPath $AliasesFile) {
        $Trimmed = $Line.Trim()
        if ($Trimmed.Length -eq 0 -or $Trimmed.StartsWith("#")) {
            continue
        }
        $Parts = $Trimmed -split '\s+'
        if ($Parts.Count -lt 2) {
            continue
        }
        $Rows += [pscustomobject] @{
            Canon = $Parts[0]
            Mib = $Parts[1]
            Aliases = @($Parts | Select-Object -Skip 2)
        }
    }

    $Rows = @($Rows | Sort-Object Canon)
    $AliasMap = @{}
    $UnicodeExpr = [System.Collections.Generic.List[string]]::new()
    $Sb = [System.Text.StringBuilder]::new()
    [void] $Sb.AppendLine("/*")
    [void] $Sb.AppendLine(" * Generated by ports/netsurf/build-leonos-probe.ps1")
    [void] $Sb.AppendLine(" */")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine("static parserutils_charset_aliases_canon canonical_charset_names[] = {")
    for ($Index = 0; $Index -lt $Rows.Count; $Index += 1) {
        $Row = $Rows[$Index]
        [void] $Sb.AppendLine(("`t{{ {0}, {1}, `"{2}`" }}," -f $Row.Mib, $Row.Canon.Length, (Escape-CString $Row.Canon)))
        if ($Row.Canon -match '^ISO-10646-UCS-[24]$' -or
            $Row.Canon -match '^UTF-16' -or
            $Row.Canon -match '^UTF-8$' -or
            $Row.Canon -match '^UTF-32') {
            [void] $UnicodeExpr.Add(("((x) == {0})" -f $Row.Mib))
        }
        $AliasMap[(ConvertTo-AliasKey $Row.Canon)] = $Index
        foreach ($Alias in $Row.Aliases) {
            $AliasMap[(ConvertTo-AliasKey $Alias)] = $Index
        }
    }
    [void] $Sb.AppendLine("};")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine(("static const uint16_t charset_aliases_canon_count = {0};" -f $Rows.Count))
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine("typedef struct {")
    [void] $Sb.AppendLine("`tuint16_t name_len;")
    [void] $Sb.AppendLine("`tconst char *name;")
    [void] $Sb.AppendLine("`tparserutils_charset_aliases_canon *canon;")
    [void] $Sb.AppendLine("} parserutils_charset_aliases_alias;")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine("static parserutils_charset_aliases_alias charset_aliases[] = {")
    foreach ($AliasKey in ($AliasMap.Keys | Sort-Object)) {
        [void] $Sb.AppendLine(("`t{{ {0}, `"{1}`", &canonical_charset_names[{2}] }}," -f $AliasKey.Length, $AliasKey, $AliasMap[$AliasKey]))
    }
    [void] $Sb.AppendLine("};")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine(("static const uint16_t charset_aliases_count = {0};" -f $AliasMap.Count))
    [void] $Sb.AppendLine()
    $Unicode = if ($UnicodeExpr.Count -gt 0) { [string]::Join(" || ", $UnicodeExpr) } else { "0" }
    [void] $Sb.AppendLine(("#define MIBENUM_IS_UNICODE(x) ({0})" -f $Unicode))

    [System.IO.File]::WriteAllText($AliasesInc, $Sb.ToString(), [System.Text.Encoding]::ASCII)
    if (-not (Test-Path -LiteralPath $AliasesInc)) {
        throw "libparserutils aliases.inc was not generated."
    }
}

function Ensure-HubbubGeneratedFiles {
    $HubbubRoot = Join-Path $VendorPath "libhubbub"
    $EntitiesInc = Join-Path $HubbubRoot "src\tokeniser\entities.inc"
    $ElementTypeInc = Join-Path $HubbubRoot "src\treebuilder\autogenerated-element-type.c"

    $EntitiesFile = Join-Path $HubbubRoot "build\Entities"
    if (-not (Test-Path -LiteralPath $EntitiesFile)) {
        throw "libhubbub entities source missing at $EntitiesFile."
    }

    $Entities = @{}
    foreach ($Line in Get-Content -LiteralPath $EntitiesFile) {
        $Trimmed = $Line.Trim()
        if ($Trimmed.Length -eq 0 -or $Trimmed.StartsWith("#")) {
            continue
        }
        $Parts = $Trimmed -split '\s+'
        if ($Parts.Count -lt 2) {
            continue
        }
        $Entities[$Parts[0]] = $Parts[1]
    }

    $script:HubbubEntityHeapIndex = 0
    $script:HubbubEntityNodes = [System.Collections.Generic.List[object]]::new()

    function New-HubbubEntityNode {
        param([string] $Pivot)

        $Node = [pscustomobject] @{
            Pivot = $Pivot
            HeapIndex = $script:HubbubEntityHeapIndex
            Lt = $null
            Eq = $null
            Gt = $null
            Value = $null
        }
        $script:HubbubEntityHeapIndex += 1
        [void] $script:HubbubEntityNodes.Add($Node)
        return $Node
    }

    function Add-HubbubEntityNode {
        param(
            $Parent,
            [string] $Key,
            [string] $Code
        )

        if ($Key.Length -eq 0) {
            $Pivot = ""
            $Tail = ""
        } elseif ($Key.Length -eq 1) {
            $Pivot = $Key
            $Tail = ""
        } else {
            $Pivot = $Key.Substring(0, 1)
            $Tail = $Key.Substring(1)
        }

        if ($null -eq $Parent) {
            $Parent = New-HubbubEntityNode -Pivot $Pivot
        }

        $Compare = [string]::CompareOrdinal($Pivot, [string] $Parent.Pivot)
        if ($Compare -lt 0) {
            $Parent.Lt = Add-HubbubEntityNode -Parent $Parent.Lt -Key $Key -Code $Code
        } elseif ($Compare -eq 0) {
            if ($Pivot -eq "") {
                $Parent.Value = $Code
            } elseif ($Tail.Length -eq 0) {
                $Parent.Value = $Code
                $Parent.Eq = Add-HubbubEntityNode -Parent $Parent.Eq -Key $Tail -Code $Code
            } else {
                $Parent.Eq = Add-HubbubEntityNode -Parent $Parent.Eq -Key $Tail -Code $Code
            }
        } else {
            $Parent.Gt = Add-HubbubEntityNode -Parent $Parent.Gt -Key $Key -Code $Code
        }

        return $Parent
    }

    $Trie = $null
    foreach ($Key in ($Entities.Keys | Sort-Object)) {
        $Trie = Add-HubbubEntityNode -Parent $Trie -Key $Key -Code $Entities[$Key]
    }

    $Sb = [System.Text.StringBuilder]::new()
    [void] $Sb.AppendLine("/*")
    [void] $Sb.AppendLine(" * This file is part of Hubbub.")
    [void] $Sb.AppendLine(" * Generated by ports/netsurf/build-leonos-probe.ps1")
    [void] $Sb.AppendLine(" */")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine("static hubbub_entity_node dict[] = {")
    foreach ($Node in $script:HubbubEntityNodes) {
        $Split = if ($Node.Pivot -eq "") { 0 } else { [int] [char] $Node.Pivot[0] }
        $Lt = if ($null -eq $Node.Lt) { -1 } else { $Node.Lt.HeapIndex }
        $Eq = if ($null -eq $Node.Eq) { -1 } else { $Node.Eq.HeapIndex }
        $Gt = if ($null -eq $Node.Gt) { -1 } else { $Node.Gt.HeapIndex }
        $Value = if ($null -eq $Node.Value) { "0" } else { $Node.Value }
        [void] $Sb.AppendLine(("`t{{ {0}, {1}, {2}, {3}, {4} }}," -f $Split, $Lt, $Eq, $Gt, $Value))
    }
    [void] $Sb.AppendLine("};")
    [void] $Sb.AppendLine()
    [void] $Sb.AppendLine(("static int32_t dict_root = {0};" -f $Trie.HeapIndex))

    [System.IO.File]::WriteAllText($EntitiesInc, $Sb.ToString(), [System.Text.Encoding]::ASCII)
    if (-not (Test-Path -LiteralPath $EntitiesInc)) {
        throw "libhubbub entities.inc was not generated."
    }

    $ElementGperf = Join-Path $HubbubRoot "src\treebuilder\element-type.gperf"
    if (-not (Test-Path -LiteralPath $ElementGperf)) {
        throw "libhubbub element type source missing at $ElementGperf."
    }

    function Escape-HubbubCString {
        param([string] $Value)
        return (($Value -replace '\\', '\\') -replace '"', '\"')
    }

    $Rows = @()
    $InWords = $false
    foreach ($Line in Get-Content -LiteralPath $ElementGperf) {
        $Trimmed = $Line.Trim()
        if ($Trimmed -eq "%%") {
            $InWords = -not $InWords
            continue
        }
        if (-not $InWords -or $Trimmed.Length -eq 0 -or $Trimmed.StartsWith("#")) {
            continue
        }
        $Parts = $Trimmed -split ',', 2
        if ($Parts.Count -ne 2) {
            continue
        }
        $Rows += [pscustomobject] @{
            Name = $Parts[0].Trim()
            Type = $Parts[1].Trim()
        }
    }
    if ($Rows.Count -eq 0) {
        throw "libhubbub element type generator found no rows."
    }

    $ElementSb = [System.Text.StringBuilder]::new()
    [void] $ElementSb.AppendLine("/*")
    [void] $ElementSb.AppendLine(" * This file is part of Hubbub.")
    [void] $ElementSb.AppendLine(" * Generated by ports/netsurf/build-leonos-probe.ps1")
    [void] $ElementSb.AppendLine(" */")
    [void] $ElementSb.AppendLine()
    [void] $ElementSb.AppendLine("#include <string.h>")
    [void] $ElementSb.AppendLine("#include <strings.h>")
    [void] $ElementSb.AppendLine()
    [void] $ElementSb.AppendLine("static const struct element_type_map wordlist[] = {")
    foreach ($Row in $Rows) {
        [void] $ElementSb.AppendLine(("`t{{ `"{0}`", {1} }}," -f (Escape-HubbubCString $Row.Name), $Row.Type))
    }
    [void] $ElementSb.AppendLine("};")
    [void] $ElementSb.AppendLine()
    [void] $ElementSb.AppendLine("static const struct element_type_map *")
    [void] $ElementSb.AppendLine("hubbub_element_type_generated_lookup(const char *str, size_t len)")
    [void] $ElementSb.AppendLine("{")
    [void] $ElementSb.AppendLine("`tfor (size_t i = 0; i < sizeof(wordlist) / sizeof(wordlist[0]); i += 1) {")
    [void] $ElementSb.AppendLine("`t`tif (strlen(wordlist[i].name) == len &&")
    [void] $ElementSb.AppendLine("`t`t`tstrncasecmp(wordlist[i].name, str, len) == 0) {")
    [void] $ElementSb.AppendLine("`t`t`treturn &wordlist[i];")
    [void] $ElementSb.AppendLine("`t`t}")
    [void] $ElementSb.AppendLine("`t}")
    [void] $ElementSb.AppendLine("`treturn NULL;")
    [void] $ElementSb.AppendLine("}")

    [System.IO.File]::WriteAllText($ElementTypeInc, $ElementSb.ToString(), [System.Text.Encoding]::ASCII)
    if (-not (Test-Path -LiteralPath $ElementTypeInc)) {
        throw "libhubbub autogenerated-element-type.c was not generated."
    }
}

function Ensure-LibDomInstalledHeaders {
    $DomRoot = Join-Path $VendorPath "libdom"
    $Bindings = @(
        [pscustomobject] @{
            Source = Join-Path $DomRoot "bindings\xml"
            Target = Join-Path $DomRoot "include\dom\bindings\xml"
            Files = @("xmlparser.h", "xmlerror.h")
        },
        [pscustomobject] @{
            Source = Join-Path $DomRoot "bindings\hubbub"
            Target = Join-Path $DomRoot "include\dom\bindings\hubbub"
            Files = @("parser.h", "errors.h")
        }
    )

    foreach ($Binding in $Bindings) {
        if (-not (Test-Path -LiteralPath $Binding.Source)) {
            throw "libdom binding source missing at $($Binding.Source)."
        }

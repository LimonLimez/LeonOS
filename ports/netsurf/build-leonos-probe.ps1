function Get-LeonOsHostCCompiler {
    $Compiler = Find-LeonOsCommand `
        -Names @("clang.exe", "clang", "gcc.exe", "gcc") `
        -Candidates @(
            (Join-Path $LeonOsLocalLlvm "clang.exe"),
            (Join-Path $LeonOsLocalLlvm "gcc.exe")
        )

    if (-not $Compiler) {
        throw "A host C compiler was not found for NetSurf generated build tools."
    }

    return $Compiler
}

function Ensure-LibCssGeneratedFiles {
    $CssRoot = Join-Path $VendorPath "libcss"
    $PropertiesDir = Join-Path $CssRoot "src\parse\properties"
    $PropertiesGen = Join-Path $PropertiesDir "properties.gen"
    $GeneratorSrc = Join-Path $PropertiesDir "css_property_parser_gen.c"
    if (-not (Test-Path -LiteralPath $PropertiesGen)) {
        throw "libcss properties.gen missing at $PropertiesGen."
    }
    if (-not (Test-Path -LiteralPath $GeneratorSrc)) {
        throw "libcss property generator source missing at $GeneratorSrc."
    }
    $ExistingGenerated = @(Get-ChildItem -LiteralPath $PropertiesDir `
        -Filter "autogenerated_*.c" -ErrorAction SilentlyContinue)
    if ($ExistingGenerated.Count -ge 100) {
        Write-Host "LeonOS NetSurf probe: reusing existing libcss generated property parsers."
        return
    }

    $HostDir = Join-Path $Out "host"
    New-Item -ItemType Directory -Path $HostDir -Force | Out-Null
    $GeneratorExe = Join-Path $HostDir "css-gen-parser.exe"
    $HostCc = Get-LeonOsHostCCompiler
    & $HostCc $GeneratorSrc "-O2" "-o" $GeneratorExe
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $GeneratorExe)) {
        if (Test-Path -LiteralPath $GeneratorExe) {
            Write-Host "LeonOS NetSurf probe: reusing existing libcss host property generator after host compile failure."
        } else {
            throw "Failed to build libcss host property generator."
        }
    }

    foreach ($Line in Get-Content -LiteralPath $PropertiesGen) {
        $Trimmed = $Line.Trim()
        if ($Trimmed.Length -eq 0 -or $Trimmed.StartsWith("#")) {
            continue
        }
        $Colon = $Trimmed.IndexOf(":")
        if ($Colon -le 0) {
            continue
        }
        $PropertyName = $Trimmed.Substring(0, $Colon)

            "WITH_LEONOS_FETCHER",
            "WITH_LEONOS_STB_IMAGE",
            "WITH_BMP",
            "WITH_GIF"
        ) + $(if ($UseQuickJsCore) {
            @(
                "LEONOS_NETSURF_QUICKJS_CORE",
                "LEONOS_QUICKJS_NO_ATOMICS",
                "LEONOS_QUICKJS_NO_STACK_CHECK",
                "LEONOS_QUICKJS_NO_MALLOC_USABLE_SIZE",
                "alloca=__builtin_alloca",
                "CONFIG_VERSION=\`"$QuickJsVersion\`"",
                "_GNU_SOURCE"
            )
        } elseif ($NoJavaScript) { @() } else {
            @(
                "DUK_OPT_HAVE_CUSTOM_H"
            )
        })
    }
}

function Get-LeonOsProbeLib {
    param([string] $Name)

    if ($Name -eq "netsurf-monkey") {
        return Get-LeonOsNetSurfMonkeyConfig
    }

    $Repo = Join-Path $VendorPath $Name
    $Src = Join-Path $Repo "src"
    $Inc = Join-Path $Repo "include"
    if (-not (Test-Path -LiteralPath $Src)) {
        throw "$Name source missing at $Src. Run ports\netsurf\fetch-netsurf.ps1 first."
    }

    switch ($Name) {
        "libwapcaplet" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
                Includes = @($Inc, $Src)
            }
        }
        "libparserutils" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
                Includes = @($Inc, $Src)
                Defines = @("WITHOUT_ICONV_FILTER")
            }
        }
        "libhubbub" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File |
                    Where-Object { $_.Name -ne "autogenerated-element-type.c" } |
                    Select-Object -ExpandProperty FullName)
                Includes = @(
                    $Inc,
                    $Src,
                    (Join-Path $VendorPath "libparserutils\include"),
                    (Join-Path $VendorPath "libwapcaplet\include")
                )
            }
        }
        "libcss" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File |
                    Where-Object { $_.Name -ne "css_property_parser_gen.c" } |
                    Select-Object -ExpandProperty FullName)
                Includes = @(
                    $Inc,
                    $Src,
                    (Join-Path $VendorPath "libparserutils\include"),
                    (Join-Path $VendorPath "libwapcaplet\include")
                )
            }
        }
        "libdom" {
            $DomSources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
            $DomSources += (Join-Path $Repo "bindings\hubbub\parser.c")
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = $DomSources
                Includes = @(
                    $Inc,
                    $Src,
                    (Join-Path $Repo "bindings\hubbub"),
                    (Join-Path $VendorPath "libparserutils\include"),
                    (Join-Path $VendorPath "libhubbub\include"),
                    (Join-Path $VendorPath "libwapcaplet\include")
                )
            }
        }
        "libnsbmp" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
                Includes = @($Inc, $Src)
            }
        }
        "libnsgif" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
                Includes = @($Inc, $Src)
            }
        }
        "libsvgtiny" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File |
                    Where-Object { $_.Name -ne "autogenerated_colors.c" } |
                    Select-Object -ExpandProperty FullName)
                Includes = @(
                    $Inc,
                    $Src,
                    (Join-Path $VendorPath "libdom\include"),
                    (Join-Path $VendorPath "libhubbub\include"),
                    (Join-Path $VendorPath "libparserutils\include"),
                    (Join-Path $VendorPath "libwapcaplet\include")
                )
            }
        }
        "libnsutils" {
            return [pscustomobject] @{
                Name = $Name
                Repo = $Repo
                Sources = @(Get-ChildItem -LiteralPath $Src -Recurse -Filter "*.c" -File | Select-Object -ExpandProperty FullName)
                Includes = @($Inc, $Src)
                Defines = @("_GNU_SOURCE", "_DEFAULT_SOURCE", "_POSIX_C_SOURCE=200809L")
            }
        }
        default {
            throw "Unknown NetSurf probe library '$Name'."
        }
    }
}

function Invoke-LeonOsCompile {
    param(
        [string] $Source,
        [string] $Object,
        [string[]] $Includes,
        [string[]] $Defines = @()
    )

    $Args = @()
    if ($Toolchain.Kind -eq "clang-lld") {
        $Args += "--target=i686-elf"
    }
    $Args += @(
        "-std=c99",
        "-Os",
        "-ffreestanding",
        "-fno-builtin",
        "-fno-stack-protector",
        "-m32",
        "-mno-sse",
        "-mno-mmx",
        "-nostdinc",
        "-isystem", $LibcInc
    )
    $Args += "-D_ALIGNED=__attribute__((aligned))"
    $Args += "-DSTMTEXPR=1"
    foreach ($Define in $Defines) {
        $Args += "-D$Define"
    }
    foreach ($Include in $Includes) {
        $Args += @("-I", $Include)
    }
    $Args += @("-c", $Source, "-o", $Object)

    & $Toolchain.Cc @Args
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to compile $Source for LeonOS NetSurf probe."
    }
}

$Objects = [System.Collections.Generic.List[string]]::new()
if ($Libraries -contains "libparserutils") {
    Ensure-LibParserUtilsGeneratedFiles
}
if ($Libraries -contains "libhubbub") {
    Ensure-HubbubGeneratedFiles
}
if (($Libraries -contains "libdom") -or ($Libraries -contains "libsvgtiny")) {
    Ensure-LibDomInstalledHeaders
}
if ($Libraries -contains "libsvgtiny") {
    Ensure-LibSvgTinyGeneratedFiles
}
if ($Libraries -contains "libcss") {
    Ensure-LibCssGeneratedFiles
}
if ($Libraries -contains "netsurf-monkey") {
    Ensure-NetSurfLeonOsSourcePatches
    Ensure-NetSurfGeneratedFiles
    if ((-not $NoJavaScript) -and (-not $UseQuickJsCore)) {
        Ensure-NetSurfDuktapeGeneratedFiles
    }
}

$LibcOut = Join-Path $Out "leonos_libc"
New-Item -ItemType Directory -Path $LibcOut -Force | Out-Null
Invoke-LeonOsCompile -Source $LibcSrc -Object (Join-Path $LibcOut "leostd.o") `
    -Includes @($Out)
[void] $Objects.Add((Join-Path $LibcOut "leostd.o"))
$SetjmpObj = Join-Path $LibcOut "setjmp-i386.o"
& $Nasm "-f" "elf32" $LibcSetjmpSrc "-o" $SetjmpObj
if ($LASTEXITCODE -ne 0) {
    throw "NASM failed while assembling the LeonOS libc setjmp/longjmp object."
}
[void] $Objects.Add($SetjmpObj)

foreach ($Library in $Libraries) {
    $Config = Get-LeonOsProbeLib $Library
    $LibOut = Join-Path $Out $Config.Name
    New-Item -ItemType Directory -Path $LibOut -Force | Out-Null
    $Compiled = 0
    foreach ($Source in $Config.Sources) {
        $Relative = $Source.Substring($Config.Repo.Length).TrimStart('\', '/')
        $ObjectName = ($Relative -replace '[\\/:]', '_') -replace '\.c$', '.o'
        $Object = Join-Path $LibOut $ObjectName
        $Defines = @()
        if ($Config.PSObject.Properties.Match("Defines").Count -gt 0) {
            $Defines = @($Config.Defines)
        }
        Invoke-LeonOsCompile -Source $Source -Object $Object -Includes $Config.Includes -Defines $Defines
        [void] $Objects.Add($Object)
        $Compiled += 1
    }
    Write-Host ("LeonOS NetSurf probe: compiled {0} objects for {1}" -f $Compiled, $Config.Name)
}

$Manifest = Join-Path $Out "objects.txt"
[System.IO.File]::WriteAllLines($Manifest, $Objects)
Write-Host ("LeonOS NetSurf probe: compiled {0} total objects to {1}" -f $Objects.Count, $Out)

if ($Libraries -contains "netsurf-monkey") {
    $LinkedObjects = @($Objects | Where-Object { $_ -notmatch '[\\/]libsvgtiny[\\/]' })
    $LinkRsp = Join-Path $Out "objects-no-svg.rsp"
    $LinkRspLines = @($LinkedObjects | ForEach-Object { '"' + $_ + '"' })
    [System.IO.File]::WriteAllLines($LinkRsp, $LinkRspLines, [System.Text.Encoding]::ASCII)

    $LinkedElf = Join-Path $Out "netsurf-monkey.elf"
    & $Toolchain.Ld "-m" "elf_i386" "-e" "main" "@$LinkRsp" "-o" $LinkedElf
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $LinkedElf)) {
        throw "Failed to link LeonOS NetSurf monkey probe executable."
    }
    Write-Host ("LeonOS NetSurf probe: linked {0} browser objects to {1}" -f $LinkedObjects.Count, $LinkedElf)

    $LeoOut = Join-Path $Out "leo1"
    New-Item -ItemType Directory -Path $LeoOut -Force | Out-Null
    $LeoCrtObj = Join-Path $LeoOut "crt0.o"
    $LeoLibcObj = Join-Path $LeoOut "leostd-user.o"
    $LeoSetjmpObj = Join-Path $LeoOut "setjmp-i386.o"
    $LeoFetchObj = Join-Path $LeoOut "leonos-fetch-user.o"
    $LeoMainObj = Join-Path $LeoOut "netsurf-leo1-main.o"
    $LeoElf = Join-Path $Out "NETSURF.elf"
    $LeoBin = Join-Path $Out "NETSURF.LEO"

    & $Nasm "-f" "elf32" (Join-Path $Root "src32\user\crt0.asm") "-o" $LeoCrtObj
    if ($LASTEXITCODE -ne 0) {
        throw "NASM failed while assembling the NetSurf LEO1 crt0."
    }

    Invoke-LeonOsCompile -Source $LibcSrc -Object $LeoLibcObj `
        -Includes @($Src32Include, $Out) -Defines @("LEONOS_USER_APP")
    & $Nasm "-f" "elf32" $LibcSetjmpSrc "-o" $LeoSetjmpObj
    if ($LASTEXITCODE -ne 0) {
        throw "NASM failed while assembling the NetSurf LEO1 setjmp/longjmp object."
    }
    $LeoNetSurfRoot = Join-Path $VendorPath "netsurf"
    $LeoGeneratedRoot = Join-Path $Out "netsurf-generated"
    Invoke-LeonOsCompile -Source $LeoFetchSrc -Object $LeoFetchObj `
        -Includes @(
            $Src32Include,
            $LeoGeneratedRoot,
            $LeoNetSurfRoot,
            (Join-Path $LeoNetSurfRoot "include"),
            (Join-Path $LeoNetSurfRoot "content\handlers"),
            (Join-Path $LeoNetSurfRoot "frontends"),
            (Join-Path $VendorPath "libwapcaplet\include")
        ) -Defines @("LEONOS_USER_APP")
    Invoke-LeonOsCompile -Source $Leo1MainSrc -Object $LeoMainObj `
        -Includes @($Src32Include, $Out) -Defines @("LEONOS_USER_APP")

    $LeoBrowserObjects = @($LinkedObjects | Where-Object {
        $_ -notmatch '[\\/]leonos_libc[\\/]leostd\.o$' -and
        $_ -notmatch '[\\/]leonos_libc[\\/]setjmp-i386\.o$' -and
        $_ -notmatch 'leonos_fetch\.o$'
    })
    $LeoObjects = @($LeoCrtObj, $LeoMainObj, $LeoLibcObj, $LeoSetjmpObj, $LeoFetchObj) +
        $LeoBrowserObjects
    $LeoRsp = Join-Path $Out "leo1-objects.rsp"
    [System.IO.File]::WriteAllLines(
        $LeoRsp,
        @($LeoObjects | ForEach-Object { '"' + $_ + '"' }),
        [System.Text.Encoding]::ASCII)

    & $Toolchain.Ld "-m" "elf_i386" "-T" (Join-Path $Root "src32\user\leonos_user.ld") `
        "-nostdlib" "-Map" (Join-Path $Out "NETSURF.link.map") `
        "-o" $LeoElf "@$LeoRsp"
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $LeoElf)) {
        throw "Failed to link NetSurf as a LeonOS LEO1 user app."
    }

    & $Toolchain.Objcopy "-O" "binary" $LeoElf $LeoBin
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $LeoBin)) {
        throw "objcopy failed while producing NETSURF.LEO."
    }
    $LeoBytes = Sync-Leo1ImageSize ([System.IO.File]::ReadAllBytes($LeoBin))
    [System.IO.File]::WriteAllBytes($LeoBin, $LeoBytes)
    if ($LeoBytes.Length -lt 32 -or
        $LeoBytes[0] -ne 0x4C -or $LeoBytes[1] -ne 0x45 -or
        $LeoBytes[2] -ne 0x4F -or $LeoBytes[3] -ne 0x31) {
        throw "NETSURF.LEO is missing the LEO1 header."
    }
    if ($LeoBytes[4] -ne 0x02) {
        throw "NETSURF.LEO must declare LEO1 ABI version 2."
    }
    Write-Host ("LeonOS NetSurf probe: linked real LEO1 smoke app {0} ({1} bytes)" -f $LeoBin, $LeoBytes.Length)
}

    New-Item -ItemType Directory -Path $DuktapeOut -Force | Out-Null

    Push-Location (Join-Path $NetSurfRoot "content\handlers\javascript\duktape")
    try {
        & $Nsgenbind -D -I "..\WebIDL" "netsurf.bnd" $DuktapeOut *> (Join-Path $DuktapeOut "nsgenbind.log")

            throw "nsgenbind failed while generating Duktape bindings. See $DuktapeOut\nsgenbind.log."
        }
    } finally {
        Pop-Location
    }

    foreach ($Required in @("binding.c", "binding.h", "private.h", "prototype.h", "Makefile")) {
        $RequiredPath = Join-Path $DuktapeOut $Required
        if (-not (Test-Path -LiteralPath $RequiredPath)) {
            throw "nsgenbind did not generate $RequiredPath."
        }
    }

    Write-NetSurfCByteInclude `
        -InputPath (Join-Path $NetSurfRoot "content\handlers\javascript\duktape\generics.js") `
        -OutputPath (Join-Path $DuktapeOut "generics.js.inc") `
        -SymbolName "generics_js"
